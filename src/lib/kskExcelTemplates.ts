const toCleanAsciiUpper = (s: string): string =>
  String(s || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/gi, 'd')
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');

// Bảng tra cứu từ tiêu đề tiếng Việt (Row0) sang mã trường chuẩn (Row1)
const VIETNAMESE_TITLE_TO_KEY_BY_TYPE: Record<KskType, Record<string, string>> = {
  Adult: {},
  Minor: {},
  ChildUnder: {},
};

(['Adult', 'Minor', 'ChildUnder'] as const).forEach(tp => {
  const spec = KSK_EXCEL_TEMPLATES[tp];
  spec.row0.forEach((title, idx) => {
    const code = spec.row1[idx];
    if (title && code) {
      const cleanTitle = toCleanAsciiUpper(title);
      if (cleanTitle && !VIETNAMESE_TITLE_TO_KEY_BY_TYPE[tp][cleanTitle]) {
        VIETNAMESE_TITLE_TO_KEY_BY_TYPE[tp][cleanTitle] = KSK_COLUMN_ALIASES[code] || code;
      }
    }
  });
});

/**
 * Chuẩn hóa tên cột từ file Excel:
 * - Chuyển khoảng trắng, gạch ngang, dấu câu thành dấu gạch dưới "_" (VD: "NOI KHOA TUAN HOAN" -> "NOI_KHOA_TUAN_HOAN")
 * - Ánh xạ các bí danh và tiêu đề tiếng Việt sang khóa chuẩn
 */
export function normalizeKskColumnKey(
  rawKey: any,
  headerTitle?: any,
  type: KskType = 'Adult'
): string {
  const kClean = toCleanAsciiUpper(String(rawKey ?? ''));
  if (kClean) {
    if (KSK_COLUMN_ALIASES[kClean]) return KSK_COLUMN_ALIASES[kClean];
    if (VIETNAMESE_TITLE_TO_KEY_BY_TYPE[type]?.[kClean]) return VIETNAMESE_TITLE_TO_KEY_BY_TYPE[type][kClean];
    return kClean;
  }
  const hClean = toCleanAsciiUpper(String(headerTitle ?? ''));
  if (hClean) {
    if (KSK_COLUMN_ALIASES[hClean]) return KSK_COLUMN_ALIASES[hClean];
    if (VIETNAMESE_TITLE_TO_KEY_BY_TYPE[type]?.[hClean]) return VIETNAMESE_TITLE_TO_KEY_BY_TYPE[type][hClean];
  }
  return '';
}

/* ------------------------------ XUẤT EXCEL ĐÚNG MẪU ------------------------------ */

const REVERSE_ALIASES: Record<string, string[]> = {};
Object.entries(KSK_COLUMN_ALIASES).forEach(([from, to]) => {
  (REVERSE_ALIASES[to] = REVERSE_ALIASES[to] || []).push(from);
});

/** Lấy giá trị của 1 cột mẫu từ dữ liệu bản ghi (thử khóa chuẩn và các khóa tương đương) */
function pickValue(data: Record<string, any>, key: string): any {
  const candidates = [key, KSK_COLUMN_ALIASES[key], ...(REVERSE_ALIASES[key] || [])].filter(Boolean) as string[];
  for (const k of candidates) {
    const v = data[k];
    if (v !== undefined && v !== null && String(v) !== '' && typeof v !== 'object') return v;
  }
  return '';
}

/**
 * Tạo dữ liệu sheet đúng 100% mẫu quy định: dòng 1 = tiêu đề tiếng Việt, dòng 2 = mã trường,
 * mọi cột của mẫu đều được giữ (cột không có dữ liệu để trống).
 */
export function buildKskExportAoa(type: KskType, records: Array<Record<string, any>>): any[][] {
  const spec = KSK_EXCEL_TEMPLATES[type];
  const aoa: any[][] = [spec.row0.slice(), spec.row1.slice()];
  records.forEach((data, idx) => {
    let seenDienThoai = false;
    const row = spec.row1.map((key, col) => {
      if (col === 0) return idx + 1;
      if (!key) return '';
      if (key === 'DIEN_THOAI') {
        if (!seenDienThoai) {
          seenDienThoai = true;
          return pickValue(data, 'DIEN_THOAI');
        }
        return pickValue(data, 'DIEN_THOAI_NGH') || pickValue(data, 'DIEN_THOAI');
      }
      if (key === 'CHI_SO_BMI') return pickValue(data, 'CHI_SO_BMI') || pickValue(data, 'BMI');
      return pickValue(data, key);
    });
    aoa.push(row);
  });
  return aoa;
}

/** Sheet DM_CanLamSang: mỗi dịch vụ CLS là 1 dòng, gắn với bệnh nhân qua Họ tên + CCCD */
export function buildKskClsExportAoa(records: Array<Record<string, any>>): any[][] {
  const aoa: any[][] = [CLS_EXCEL_TEMPLATE.row0.slice(), CLS_EXCEL_TEMPLATE.row1.slice()];
  let tt = 0;
  records.forEach(data => {
    const list: any[] = Array.isArray(data.CLS) ? data.CLS : [];
    list.forEach(c => {
      tt += 1;
      aoa.push([
        tt,
        data.HO_TEN || '',
        data.SO_CCCD || '',
        c.TEN_CHI_SO || c.MA_CHI_SO || '',
        c.MA_DICH_VU || '',
        c.DON_VI_DO || '',
        c.GIA_TRI || '',
        c.MO_TA || '',
        c.KET_LUAN || '',
      ]);
    });
  });
  return aoa;
}

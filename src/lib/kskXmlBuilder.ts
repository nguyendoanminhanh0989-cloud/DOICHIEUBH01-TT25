export function buildKskXml(records: any[], maCskcb: string): string {
  const currentDate = new Date();
  const ngayLap = currentDate.getFullYear().toString() +
    String(currentDate.getMonth() + 1).padStart(2, '0') +
    String(currentDate.getDate()).padStart(2, '0');

  let xml = '<?xml version="1.0" encoding="utf-8"?>\n';
  xml += '<KHAMSUCKHOE xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:xsd="http://www.w3.org/2001/XMLSchema">\n';
  xml += '  <THONGTINDONVI>\n';
  xml += `    <MACSKCB>${maCskcb}</MACSKCB>\n`;
  xml += '  </THONGTINDONVI>\n';
  xml += '  <THONGTINHOSO>\n';
  xml += `    <NGAYLAP>${ngayLap}</NGAYLAP>\n`;
  xml += `    <SOLUONGHOSO>${records.length}</SOLUONGHOSO>\n`;
  xml += '    <DANHSACHHOSO>\n';

  records.forEach((record) => {
    xml += '      <HOSO>\n';
    
    let xmlIndex = 1;
    for (const [sectionName, tags] of Object.entries(XML_SECTIONS)) {
      xml += '        <FILEHOSO>\n';
      xml += `          <LOAIHOSO>XML${xmlIndex}</LOAIHOSO>\n`;
      xml += '          <NOIDUNGFILE>\n';
      xml += `            <${sectionName}>\n`;
      
      for (const tag of tags) {
        if (record[tag] !== undefined && record[tag] !== '') {
          // Escape special characters
          const value = String(record[tag])
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;');
          xml += `              <${tag}>${value}</${tag}>\n`;
        }
      }

      xml += `            </${sectionName}>\n`;
      xml += '          </NOIDUNGFILE>\n';
      xml += '        </FILEHOSO>\n';
      xmlIndex++;
    }

    xml += '      </HOSO>\n';
  });

  xml += '    </DANHSACHHOSO>\n';
  xml += '  </THONGTINHOSO>\n';
  xml += '</KHAMSUCKHOE>';

  return xml;
}
